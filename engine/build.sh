#!/usr/bin/env bash
# Builds libglassengine.so for both Android ABIs.
#
#   ./build.sh [abi ...]     default: arm64-v8a x86_64
#
# API 30, not 36: NDK r29's sysroot stops at 35, and 30 keeps the .so loadable
# on every Android version this targets. Nothing here calls a framework API —
# the engine only needs libc, libdl and liblog.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
NDK="${ANDROID_NDK:-$HOME/Android/Sdk/ndk/29.0.14206865}"
TC="$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin"
API=30
OUT="$HERE/out"

# Embed the generated SkSL. The engine also accepts an override file on device
# for fast iteration, but embedding guarantees it always has *a* shader, and
# means a shipped .so is self-contained.
python3 "$HERE/../shader/gen_glass_sksl.py" >/dev/null
mkdir -p "$HERE/src/generated"
python3 - "$HERE/../shader/build/glass_high.sksl" "$HERE/../shader/build/glass_tone.sksl" \
  "$HERE/src/generated/glass_shader_src.h" "$HERE/../shader/build/glass_lean.sksl" \
  "$HERE/../shader/build/glass_lean_soft.sksl" "$HERE/../shader/build/glass_deep.sksl" \
  "$HERE/../shader/build/glass_tone_lean.sksl" <<'PYEOF'
import sys, pathlib
src = pathlib.Path(sys.argv[1]).read_text()
tone = pathlib.Path(sys.argv[2]).read_text()
lean = pathlib.Path(sys.argv[4]).read_text()
lean_soft = pathlib.Path(sys.argv[5]).read_text()
deep = pathlib.Path(sys.argv[6]).read_text()
tone_lean = pathlib.Path(sys.argv[7]).read_text()
# A raw string literal keeps the SkSL readable in the binary and avoids escaping
# entirely; the delimiter is chosen so it cannot occur in shader source.
import re
# The declared uniforms and children, extracted from the same source that is
# embedded, so the two can never drift. The engine looks every one of these up
# through SkRuntimeEffect::findUniform at load time: if the vendored headers
# disagree with the target's Skia, the lookups fail and the hook is refused
# rather than drawing through a mismatched layout.
#
# Some builds inline findUniform and findChild away. For those the engine
# needs each uniform's offset without asking, so this also lays the uniforms
# out the way SkRuntimeEffect does: in declaration order, each straight after
# the one before, 4 bytes a component whatever the precision
# (SkRuntimeEffectPriv::VarAsUniform; Uniform::sizeInBytes). The children are
# numbered in declaration order. The engine trusts that layout on a build only
# if the effect's uniformSize() comes out at the packed total.
SIZES = {}
for base in ('float', 'half', 'int'):
    SIZES[base] = 4
    for n in (2, 3, 4):
        SIZES['%s%d' % (base, n)] = 4 * n
for base in ('float', 'half'):
    for n in (2, 3, 4):
        SIZES['%s%dx%d' % (base, n, n)] = 4 * n * n
def decls(text):
    uni = re.findall(r'^\s*uniform\s+((?:float|half|int)[0-9x]*)\s+(\w+)\s*;', text, re.M)
    ch  = re.findall(r'^\s*uniform\s+shader\s+(\w+)\s*;', text, re.M)
    # An array, a layout() qualifier or a type this does not know would be
    # skipped by the patterns above and leave the engine a uniform short.
    declared = re.findall(r'^\s*uniform\s', text, re.M)
    assert len(declared) == len(uni) + len(ch), 'a uniform declaration this cannot parse'
    for t, n in uni:
        assert t in SIZES, 'uniform %s has a type with no known size: %s' % (n, t)
    return uni, ch
def arr(name, items):
    body = ''.join('    "%s",\n' % i for i in items)
    return ('inline constexpr const char* %s[] = {\n%s};\n'
            'inline constexpr int %s_count = %d;\n' % (name, body, name, len(items)))
def packed(name, uni):
    offsets, at = [], 0
    for t, _ in uni:
        offsets.append(at)
        at += SIZES[t]
    return ('inline constexpr unsigned %s[] = {%s};\n'
            'inline constexpr unsigned %sSize = %d;\n'
            % (name, ', '.join(str(o) for o in offsets), name, at))
uni_decl, ch = decls(src)
tone_decl, tone_ch = decls(tone)
uni = [n for _, n in uni_decl]
tone_uni = [n for _, n in tone_decl]
# The lean builds declare what HIGH declares, in its order: one uniform block
# is filled for all three.
for other in (lean, lean_soft, deep):
    assert decls(other) == (uni_decl, ch), 'a lean shader declares other uniforms than HIGH'
assert decls(tone_lean) == (tone_decl, tone_ch), 'the lean tone shader declares other uniforms'
out = ('// GENERATED by engine/build.sh from shader/build/glass_high.sksl, its\n'
       '// lean builds (glass_lean, glass_lean_soft, glass_deep) and glass_tone.sksl\n'
       '// with its own (glass_tone_lean).\n'
       '#pragma once\n'
       'namespace glass {\n'
       'inline constexpr char kGlassShaderHigh[] = R"SKSL(\n' + src + ')SKSL";\n'
       + arr('kGlassUniformNames', uni)
       + packed('kGlassUniformPacked', uni_decl)
       + arr('kGlassChildNames', ch)
       + 'inline constexpr char kGlassShaderLean[] = R"SKSL(\n' + lean + ')SKSL";\n'
       + 'inline constexpr char kGlassShaderLeanSoft[] = R"SKSL(\n' + lean_soft + ')SKSL";\n'
       + 'inline constexpr char kGlassShaderDeep[] = R"SKSL(\n' + deep + ')SKSL";\n'
       + 'inline constexpr char kGlassShaderTone[] = R"SKSL(\n' + tone + ')SKSL";\n'
       + arr('kGlassToneUniformNames', tone_uni)
       + packed('kGlassToneUniformPacked', tone_decl)
       + arr('kGlassToneChildNames', tone_ch)
       + 'inline constexpr char kGlassShaderToneLean[] = R"SKSL(\n' + tone_lean + ')SKSL";\n'
       + '}  // namespace glass\n')
pathlib.Path(sys.argv[3]).write_text(out)
PYEOF

[ -d "$HERE/vendor/skia/android" ] || {
  echo "Skia headers not vendored. Run engine/vendor/fetch_skia_headers.sh" >&2; exit 1; }

# Order matters: AOSP's SkUserConfig.h must be found before anything else, and
# include/config supplies the unqualified SkUserConfigManual.h it pulls in.
INC=(-I "$HERE/vendor/skia/android" -I "$HERE/vendor/skia" -I "$HERE/vendor/skia/include/config")

# glass_draw.cpp and sk_shared.cpp are the drawing code, which a ROM build
# (rom/) compiles too; the rest is the module's.
SRC=("$HERE/src/elf_syms.cpp" "$HERE/src/sf_symbols.cpp" "$HERE/src/sf_resolve.cpp" "$HERE/src/sf_cache.cpp" "$HERE/src/xz_inflate.cpp" \
     "$HERE/src/sk_bridge.cpp" "$HERE/src/sk_shared.cpp" "$HERE/src/glass_params.cpp" \
     "$HERE/src/glass_draw.cpp" "$HERE/src/glass_engine.cpp" \
     "$HERE/src/exec_probe.cpp" "$HERE/src/abi_check.cpp" "$HERE/src/crash_guard.cpp" \
     "$HERE/src/blur_scale.cpp")

# XZ Embedded is C, not C++: its enum arithmetic does not compile under a C++
# front end. Built separately and linked in.
XZ_C=(xz_crc32 xz_dec_lzma2 xz_dec_stream xz_dec_bcj)
# .gnu_debugdata uses a CRC32 check; BCJ filters are enabled as cheap insurance
# since omitting one would fail on some targets only.
XZ_FLAGS=(-DXZ_DEC_BCJ -DXZ_DEC_X86 -DXZ_DEC_ARM -DXZ_DEC_ARM64)

declare -A TRIPLE=([arm64-v8a]=aarch64-linux-android [x86_64]=x86_64-linux-android)
ABIS=("${@:-}")
[ -z "${ABIS[0]:-}" ] && ABIS=(arm64-v8a x86_64)

for abi in "${ABIS[@]}"; do
  t="${TRIPLE[$abi]:-}"
  [ -n "$t" ] || { echo "unknown abi: $abi" >&2; exit 1; }
  mkdir -p "$OUT/$abi/obj"
  for c in "${XZ_C[@]}"; do
    "$TC/clang" --target="$t$API" -std=c11 -O2 -fPIC -w \
      -I "$HERE/vendor/xz" "${XZ_FLAGS[@]}" \
      -c "$HERE/vendor/xz/$c.c" -o "$OUT/$abi/obj/$c.o"
  done

  # -s: the frida-gum static devkit carries ~17 MB of symbols we never expose.
  # Stripping takes the result from 20 MB to ~2-3 MB, which matters for
  # something mapped into SurfaceFlinger.
  # -static-libstdc++ is not optional here. The NDK defaults to libc++_shared.so,
  # which does not exist on a device — the platform has its own libc++ — so a
  # shared-STL build makes surfaceflinger UNLINKABLE and bootloops the device
  # before any of our code runs. Notably the bootloop guard cannot help with
  # that: the failure is in the linker, before our constructor.
  "$TC/clang++" --target="$t$API" -std=c++17 -fPIC -shared -O2 -s \
    -static-libstdc++ \
    -fvisibility=hidden -ffunction-sections -fdata-sections \
    -Wl,--gc-sections,--exclude-libs,ALL,--no-undefined \
    -Wall -Wextra -Wno-unused-parameter \
    "${INC[@]}" -I "$HERE/vendor/xz" -I "$HERE/vendor/frida-gum/$abi" \
    -o "$OUT/$abi/libglassengine.so" "${SRC[@]}" "$OUT/$abi/obj"/*.o \
    "$HERE/vendor/frida-gum/$abi/libfrida-gum.a" -llog
  # Refuse to ship anything that depends on a library the device does not have.
  # Only these are guaranteed present in surfaceflinger's linker namespace.
  allowed="libc.so|libm.so|libdl.so|liblog.so"
  bad=$(readelf -d "$OUT/$abi/libglassengine.so" \
        | sed -n 's/.*Shared library: \[\(.*\)\]/\1/p' \
        | grep -vE "^($allowed)$" || true)
  if [ -n "$bad" ]; then
    echo "FATAL: $abi depends on libraries absent from the platform:" >&2
    echo "$bad" | sed 's/^/    /' >&2
    exit 1
  fi
  printf "%-10s %s  (%s bytes)  NEEDED: %s\n" "$abi" "$OUT/$abi/libglassengine.so" \
    "$(stat -c%s "$OUT/$abi/libglassengine.so")" \
    "$(readelf -d "$OUT/$abi/libglassengine.so" | sed -n 's/.*Shared library: \[\(.*\)\]/\1/p' | tr '\n' ' ')"
done
